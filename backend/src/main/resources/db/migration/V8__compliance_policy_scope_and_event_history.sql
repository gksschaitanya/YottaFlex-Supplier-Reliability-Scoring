CREATE OR REPLACE FUNCTION compliance_record_policy_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE kind VARCHAR(16); t TIMESTAMPTZ; is_mandatory BOOLEAN; is_critical BOOLEAN;
BEGIN
 IF TG_OP='UPDATE' AND NEW.applicability_code IS NOT DISTINCT FROM OLD.applicability_code
   AND NEW.critical IS NOT DISTINCT FROM OLD.critical AND NEW.status IS NOT DISTINCT FROM OLD.status
   AND NEW.effective_from IS NOT DISTINCT FROM OLD.effective_from AND NEW.effective_to IS NOT DISTINCT FROM OLD.effective_to THEN RETURN NEW; END IF;
 IF NEW.requirement_code IN ('WORKPLACE_SAFETY','ORIGIN_DECLARATION','TRACEABILITY') THEN kind:='SITE'; ELSE kind:='SUPPLIER'; END IF;
 is_mandatory:=NEW.requirement_code IN ('BUSINESS_LICENSE','TAX_REGISTRATION','SANCTIONS_SCREEN','INSURANCE_COVER');
 is_critical:=NEW.requirement_code IN ('SANCTIONS_SCREEN','INSURANCE_COVER');
 IF NEW.requirement_code NOT IN ('BUSINESS_LICENSE','TAX_REGISTRATION','QUALITY_CERT','ENVIRONMENT_CERT','WORKPLACE_SAFETY','DATA_SECURITY','ANTI_BRIBERY','SANCTIONS_SCREEN','INSURANCE_COVER','ORIGIN_DECLARATION','TRACEABILITY','CONTINUITY_PLAN') THEN
   RAISE EXCEPTION 'Unsupported compliance policy code %',NEW.requirement_code;
 END IF;
 IF NEW.critical IS DISTINCT FROM is_critical THEN RAISE EXCEPTION 'Criticality mapping mismatch for %',NEW.requirement_code; END IF;
 IF NEW.applicability_code NOT IN ('ALL','GENERAL','SUPPLIER','SITE','SUPPLIER_OR_SITE') THEN RAISE EXCEPTION 'Unsupported applicability_code % for requirement %',NEW.applicability_code,NEW.requirement_code; END IF;
 t:=clock_timestamp();
 INSERT INTO compliance_requirement_policy_history(event_id,requirement_id,applicability_code,scope_type,mandatory,critical,active,effective_from,effective_to,recorded_at)
 VALUES(gen_random_uuid(),NEW.id,NEW.applicability_code,kind,is_mandatory,is_critical,NEW.status='ACTIVE',NEW.effective_from,NEW.effective_to,t);
 IF NEW.status='ACTIVE' THEN
   IF kind='SUPPLIER' THEN
     PERFORM s.id FROM supplier s ORDER BY s.id FOR UPDATE;
     INSERT INTO compliance_scope_requirement(scope_history_id,requirement_id)
     SELECT h.id,NEW.id FROM (
       SELECT DISTINCT ON(supplier_id) id,supplier_id,active FROM compliance_scope_history
       WHERE scope_type='SUPPLIER' AND recorded_at<=t ORDER BY supplier_id,recorded_at DESC,id DESC
     ) h WHERE h.active ON CONFLICT(scope_history_id,requirement_id) DO NOTHING;
   ELSE
     PERFORM s.id FROM supplier s ORDER BY s.id FOR UPDATE;
     INSERT INTO compliance_scope_requirement(scope_history_id,requirement_id)
     SELECT h.id,NEW.id FROM (
       SELECT DISTINCT ON(supplier_id,site_id) id,supplier_id,site_id,active FROM compliance_scope_history
       WHERE scope_type='SITE' AND recorded_at<=t ORDER BY supplier_id,site_id,recorded_at DESC,id DESC
     ) h WHERE h.active ON CONFLICT(scope_history_id,requirement_id) DO NOTHING;
   END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_compliance_requirement_policy_history AFTER INSERT OR UPDATE OF applicability_code,critical,status,effective_from,effective_to
 ON compliance_requirement FOR EACH ROW EXECUTE FUNCTION compliance_record_policy_change();

