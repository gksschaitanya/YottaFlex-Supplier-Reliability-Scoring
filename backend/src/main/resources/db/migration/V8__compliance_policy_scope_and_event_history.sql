CREATE OR REPLACE FUNCTION compliance_record_evidence_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE old_ref VARCHAR(200); new_ref VARCHAR(200); owner_assessment BIGINT; owner_check BIGINT; item BIGINT; event_time TIMESTAMPTZ;
BEGIN
 IF TG_TABLE_NAME='compliance_assessment' THEN owner_assessment:=NEW.id; old_ref:=CASE WHEN TG_OP='INSERT' THEN NULL ELSE OLD.evidence_reference END; new_ref:=NEW.evidence_reference;
 ELSE owner_check:=NEW.id; old_ref:=CASE WHEN TG_OP='INSERT' THEN NULL ELSE OLD.evidence_reference END; new_ref:=NEW.evidence_reference; END IF;
 IF old_ref IS NOT DISTINCT FROM new_ref THEN RETURN NEW; END IF;
 event_time:=clock_timestamp();
 IF old_ref IS NOT NULL THEN
  SELECT id INTO item FROM compliance_evidence_item WHERE evidence_reference=old_ref AND ((owner_assessment IS NOT NULL AND assessment_id=owner_assessment) OR (owner_check IS NOT NULL AND check_id=owner_check)) ORDER BY id DESC LIMIT 1;
  IF item IS NULL THEN INSERT INTO compliance_evidence_item(item_key,assessment_id,check_id,evidence_reference,legacy_untracked,created_at) VALUES(gen_random_uuid(),owner_assessment,owner_check,old_ref,TRUE,event_time) RETURNING id INTO item; END IF;
   INSERT INTO compliance_evidence_event(event_key,evidence_item_id,event_type,recorded_at) VALUES(gen_random_uuid()::text,item,'REVOKED',event_time);
 END IF;
 IF new_ref IS NOT NULL THEN
  INSERT INTO compliance_evidence_item(item_key,assessment_id,check_id,evidence_reference,legacy_untracked,created_at) VALUES(gen_random_uuid(),owner_assessment,owner_check,new_ref,FALSE,event_time)
  ON CONFLICT DO NOTHING;
  SELECT id INTO item FROM compliance_evidence_item WHERE evidence_reference=new_ref AND ((owner_assessment IS NOT NULL AND assessment_id=owner_assessment) OR (owner_check IS NOT NULL AND check_id=owner_check)) ORDER BY id DESC LIMIT 1;
  INSERT INTO compliance_evidence_event(event_key,evidence_item_id,event_type,recorded_at) VALUES(gen_random_uuid()::text,item,'AVAILABLE',event_time);
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_compliance_assessment_evidence_history AFTER INSERT OR UPDATE OF evidence_reference ON compliance_assessment FOR EACH ROW EXECUTE FUNCTION compliance_record_evidence_change();
CREATE TRIGGER tr_compliance_check_evidence_history AFTER INSERT OR UPDATE OF evidence_reference ON compliance_check FOR EACH ROW EXECUTE FUNCTION compliance_record_evidence_change();

CREATE OR REPLACE FUNCTION compliance_site_lifecycle_history() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE t TIMESTAMPTZ; active_now BOOLEAN; hist_id BIGINT; scope_from DATE; scope_to DATE;
BEGIN
 IF TG_OP='UPDATE' AND (NEW.supplier_id IS DISTINCT FROM OLD.supplier_id) THEN RAISE EXCEPTION 'Site supplier ownership is immutable'; END IF;
 IF TG_OP='UPDATE' AND NEW.status IS NOT DISTINCT FROM OLD.status AND NEW.effective_from IS NOT DISTINCT FROM OLD.effective_from AND NEW.effective_to IS NOT DISTINCT FROM OLD.effective_to THEN RETURN NEW; END IF;
 t:=clock_timestamp();
 PERFORM id FROM supplier WHERE id=NEW.supplier_id FOR UPDATE;
 active_now:=NEW.status='ACTIVE' AND (NEW.effective_to IS NULL OR NEW.effective_to>=t::date);
 scope_from:=CASE WHEN NEW.effective_to IS NOT NULL AND NEW.effective_to<t::date THEN NEW.effective_from ELSE GREATEST(NEW.effective_from,t::date) END;
 scope_to:=NEW.effective_to;
 INSERT INTO compliance_scope_history(event_id,supplier_id,scope_type,site_id,active,effective_from,effective_to,recorded_at)
 VALUES(gen_random_uuid(),NEW.supplier_id,'SITE',NEW.id,active_now,scope_from,scope_to,t) RETURNING id INTO hist_id;
 INSERT INTO compliance_scope_site(scope_history_id,supplier_id,scope_type,site_id) VALUES(hist_id,NEW.supplier_id,'SITE',NEW.id);
 INSERT INTO compliance_scope_requirement(scope_history_id,requirement_id)
 SELECT hist_id,p.requirement_id FROM (
   SELECT DISTINCT ON(requirement_id) requirement_id,scope_type,active FROM compliance_requirement_policy_history
   WHERE recorded_at<=t ORDER BY requirement_id,recorded_at DESC,id DESC
 ) p WHERE p.scope_type='SITE' AND p.active ON CONFLICT(scope_history_id,requirement_id) DO NOTHING;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_compliance_site_lifecycle_history AFTER INSERT OR UPDATE OF status,effective_from,effective_to,supplier_id ON site FOR EACH ROW EXECUTE FUNCTION compliance_site_lifecycle_history();

CREATE OR REPLACE FUNCTION compliance_supplier_scope_history() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE t TIMESTAMPTZ; scope_pk BIGINT; policy_row RECORD;
BEGIN
 t:=clock_timestamp();
 INSERT INTO compliance_scope_history(event_id,supplier_id,scope_type,site_id,active,effective_from,effective_to,recorded_at)
 VALUES(gen_random_uuid(),NEW.id,'SUPPLIER',NULL,TRUE,t::date,NULL,t) RETURNING id INTO scope_pk;
 FOR policy_row IN SELECT requirement_id FROM (SELECT DISTINCT ON(requirement_id) requirement_id,active FROM compliance_requirement_policy_history
   WHERE scope_type='SUPPLIER' AND recorded_at<=t ORDER BY requirement_id,recorded_at DESC,id DESC) latest WHERE active ORDER BY requirement_id LOOP
   INSERT INTO compliance_scope_requirement(scope_history_id,requirement_id) VALUES(scope_pk,policy_row.requirement_id) ON CONFLICT DO NOTHING;
 END LOOP;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_compliance_supplier_scope_history AFTER INSERT ON supplier FOR EACH ROW EXECUTE FUNCTION compliance_supplier_scope_history();

CREATE OR REPLACE FUNCTION compliance_prevent_site_delete_with_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN IF EXISTS(SELECT 1 FROM compliance_scope_history WHERE site_id=OLD.id) THEN RAISE EXCEPTION 'Site has compliance scope history and cannot be deleted'; END IF; RETURN OLD; END $$;
CREATE TRIGGER tr_compliance_site_history_delete_guard BEFORE DELETE ON site FOR EACH ROW EXECUTE FUNCTION compliance_prevent_site_delete_with_history();

