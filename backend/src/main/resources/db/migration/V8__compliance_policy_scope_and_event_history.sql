DO $site_baseline_validation$
DECLARE bad_sites TEXT; bad_suppliers TEXT;
BEGIN
 SELECT string_agg(s.supplier_id, ',') INTO bad_suppliers FROM supplier s CROSS JOIN compliance_history_cutover c
 WHERE s.created_at>c.cutover_at OR s.updated_at>c.cutover_at;
 IF bad_suppliers IS NOT NULL THEN RAISE EXCEPTION 'Supplier records are later than the compliance cutover snapshot: %',bad_suppliers; END IF;
 SELECT string_agg(si.site_id, ',') INTO bad_sites FROM site si CROSS JOIN compliance_history_cutover c
 WHERE si.status='ACTIVE' AND (si.created_at>c.cutover_at OR si.updated_at>c.cutover_at OR si.effective_from>c.cutover_at::date OR (si.effective_to IS NOT NULL AND si.effective_to<c.cutover_at::date));
 IF bad_sites IS NOT NULL THEN RAISE EXCEPTION 'Active sites are not eligible for prospective baseline: %',bad_sites; END IF;
END $site_baseline_validation$;
