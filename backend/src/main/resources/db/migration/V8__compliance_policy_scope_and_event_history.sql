-- Validate a populated catalog; an empty catalog is supported and policy rows are added by the insert trigger.
DO $policy_validation$
DECLARE missing_codes TEXT; mismatched_critical TEXT; unsupported_codes TEXT; unsupported_applicability TEXT;
BEGIN
 IF NOT EXISTS (SELECT 1 FROM compliance_requirement) THEN RETURN; END IF;
  SELECT string_agg(x.code, ',') INTO missing_codes FROM (VALUES
    ('BUSINESS_LICENSE'),('TAX_REGISTRATION'),('QUALITY_CERT'),('ENVIRONMENT_CERT'),('WORKPLACE_SAFETY'),('DATA_SECURITY'),
    ('ANTI_BRIBERY'),('SANCTIONS_SCREEN'),('INSURANCE_COVER'),('ORIGIN_DECLARATION'),('TRACEABILITY'),('CONTINUITY_PLAN')) x(code)
  LEFT JOIN compliance_requirement r ON r.requirement_code=x.code WHERE r.id IS NULL;
  IF missing_codes IS NOT NULL THEN RAISE EXCEPTION 'Missing approved compliance requirements: %', missing_codes; END IF;
  SELECT string_agg(r.requirement_code, ',') INTO mismatched_critical
  FROM compliance_requirement r WHERE r.requirement_code IN ('BUSINESS_LICENSE','TAX_REGISTRATION','QUALITY_CERT','ENVIRONMENT_CERT','WORKPLACE_SAFETY','DATA_SECURITY','ANTI_BRIBERY','SANCTIONS_SCREEN','INSURANCE_COVER','ORIGIN_DECLARATION','TRACEABILITY','CONTINUITY_PLAN')
   AND r.critical IS DISTINCT FROM (r.requirement_code IN ('SANCTIONS_SCREEN','INSURANCE_COVER'));
  IF mismatched_critical IS NOT NULL THEN RAISE EXCEPTION 'Existing criticality differs from approved independent map: %', mismatched_critical; END IF;
  SELECT string_agg(r.requirement_code, ',') INTO unsupported_codes FROM compliance_requirement r WHERE r.requirement_code NOT IN
   ('BUSINESS_LICENSE','TAX_REGISTRATION','QUALITY_CERT','ENVIRONMENT_CERT','WORKPLACE_SAFETY','DATA_SECURITY','ANTI_BRIBERY','SANCTIONS_SCREEN','INSURANCE_COVER','ORIGIN_DECLARATION','TRACEABILITY','CONTINUITY_PLAN');
  IF unsupported_codes IS NOT NULL THEN RAISE EXCEPTION 'Unsupported compliance catalog requirements: %',unsupported_codes; END IF;
  SELECT string_agg(r.requirement_code||'='||r.applicability_code, ',') INTO unsupported_applicability
   FROM compliance_requirement r WHERE r.applicability_code NOT IN ('ALL','GENERAL','SUPPLIER','SITE','SUPPLIER_OR_SITE');
  IF unsupported_applicability IS NOT NULL THEN RAISE EXCEPTION 'Unsupported compliance applicability values: %',unsupported_applicability; END IF;
END $policy_validation$;

