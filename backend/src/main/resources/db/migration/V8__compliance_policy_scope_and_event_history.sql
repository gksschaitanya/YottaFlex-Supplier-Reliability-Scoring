WHERE h.scope_type='SITE';

CREATE OR REPLACE FUNCTION compliance_check_scope_shape() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE scope_id BIGINT; kind VARCHAR(16); child_count BIGINT;
BEGIN
 IF TG_TABLE_NAME='compliance_scope_history' THEN
   scope_id:=CASE WHEN TG_OP='DELETE' THEN OLD.id ELSE NEW.id END;
 ELSE
   scope_id:=CASE WHEN TG_OP='DELETE' THEN OLD.scope_history_id ELSE NEW.scope_history_id END;
 END IF;
 SELECT scope_type INTO kind FROM compliance_scope_history WHERE id=scope_id;
 IF NOT FOUND THEN RETURN NULL; END IF;
 SELECT count(*) INTO child_count FROM compliance_scope_site WHERE scope_history_id=scope_id;
 IF (kind='SUPPLIER' AND child_count<>0) OR (kind='SITE' AND child_count<1) THEN
   RAISE EXCEPTION 'Invalid compliance scope header/child shape for scope %',scope_id;
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER ct_compliance_scope_header_shape AFTER INSERT OR UPDATE OR DELETE ON compliance_scope_history
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION compliance_check_scope_shape();
CREATE CONSTRAINT TRIGGER ct_compliance_scope_child_shape AFTER INSERT OR UPDATE OR DELETE ON compliance_scope_site
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION compliance_check_scope_shape();

