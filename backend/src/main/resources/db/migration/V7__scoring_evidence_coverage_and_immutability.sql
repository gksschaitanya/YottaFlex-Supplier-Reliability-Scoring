CREATE FUNCTION prevent_completed_score_run_mutation() RETURNS TRIGGER AS $$
DECLARE parent_run_id BIGINT;
DECLARE parent_status VARCHAR(16);
BEGIN
    IF TG_TABLE_NAME = 'score_run' THEN
        parent_run_id := OLD.id;
    ELSIF TG_TABLE_NAME IN ('score_run_component_config', 'score_run_classification_threshold', 'score_run_severity_config', 'score_run_source_observation_count', 'supplier_score', 'score_evidence') THEN
        IF TG_OP = 'INSERT' THEN
            parent_run_id := NEW.score_run_id;
        ELSE
            parent_run_id := OLD.score_run_id;
        END IF;
    ELSIF TG_TABLE_NAME = 'supplier_score_component' THEN
        IF TG_OP = 'INSERT' THEN
            SELECT score_run_id INTO parent_run_id FROM supplier_score WHERE id = NEW.supplier_score_id;
        ELSE
            SELECT score_run_id INTO parent_run_id FROM supplier_score WHERE id = OLD.supplier_score_id;
        END IF;
    END IF;
    IF parent_run_id IS NOT NULL THEN
        SELECT run_status INTO parent_status FROM score_run WHERE id = parent_run_id;
        IF parent_status = 'COMPLETED' THEN
            RAISE EXCEPTION 'Completed score run % is immutable', parent_run_id USING ERRCODE = '55000';
        END IF;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

