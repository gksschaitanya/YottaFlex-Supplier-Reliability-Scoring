    CONSTRAINT ck_invoice_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_invoice_status CHECK (status IN ('RECEIVED', 'MATCHED', 'DISPUTED', 'APPROVED', 'VOIDED')),
