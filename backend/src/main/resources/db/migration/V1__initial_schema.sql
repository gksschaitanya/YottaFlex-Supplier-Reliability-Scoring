CREATE TABLE data_generation_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_id VARCHAR(80) NOT NULL,
    seed BIGINT NOT NULL,
    scale VARCHAR(12) NOT NULL,
    generator_version VARCHAR(40) NOT NULL,
    reference_date DATE NOT NULL,
    config_hash CHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL,
    started_at TIMESTAMPTZ(6) NOT NULL,
    completed_at TIMESTAMPTZ(6) NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uk_generation_run_id UNIQUE (run_id),
    CONSTRAINT ck_generation_run_scale CHECK (scale IN ('STARTER', 'FULL')),
    CONSTRAINT ck_generation_run_status CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_generation_run_completion CHECK (completed_at IS NULL OR completed_at >= started_at)
);


