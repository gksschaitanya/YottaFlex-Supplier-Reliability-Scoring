ALTER TABLE staging_record ADD COLUMN corrected_payload JSONB NULL;
ALTER TABLE staging_record ADD COLUMN payload_version INTEGER NOT NULL DEFAULT 1;

CREATE TABLE validation_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    validation_run_id VARCHAR(32) NOT NULL UNIQUE,
    generation_run_id BIGINT NOT NULL REFERENCES data_generation_run(id) ON DELETE RESTRICT,
    detector_version VARCHAR(40) NOT NULL,
    run_status VARCHAR(16) NOT NULL CHECK (run_status IN ('RUNNING','COMPLETED','FAILED')),
    started_at TIMESTAMPTZ(6) NOT NULL,
    completed_at TIMESTAMPTZ(6),
    failure_reason VARCHAR(1000),
    CONSTRAINT ck_validation_run_completion CHECK ((run_status='RUNNING' AND completed_at IS NULL) OR (run_status IN ('COMPLETED','FAILED') AND completed_at IS NOT NULL))
);
CREATE INDEX ix_validation_run_generation_started ON validation_run(generation_run_id, started_at DESC);

CREATE TABLE validation_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    validation_run_id BIGINT NOT NULL REFERENCES validation_run(id) ON DELETE RESTRICT,
    staging_record_id BIGINT NOT NULL REFERENCES staging_record(id) ON DELETE RESTRICT,
    payload_version INTEGER NOT NULL,
    is_valid BOOLEAN NOT NULL,
    issue_type VARCHAR(48),
    severity VARCHAR(16),
    description VARCHAR(1000) NOT NULL,
    validated_at TIMESTAMPTZ(6) NOT NULL,
    CONSTRAINT ck_validation_result_issue CHECK ((is_valid=TRUE AND issue_type IS NULL AND severity IS NULL) OR (is_valid=FALSE AND issue_type IS NOT NULL AND severity IN ('INFO','LOW','MEDIUM','HIGH','CRITICAL'))),
    CONSTRAINT uk_validation_result_record_version UNIQUE(validation_run_id, staging_record_id, payload_version)
);
CREATE INDEX ix_validation_result_record_time ON validation_result(staging_record_id, validated_at DESC);

ALTER TABLE exception_record DROP CONSTRAINT ck_exception_resolved_at;
ALTER TABLE exception_record ADD CONSTRAINT ck_exception_resolution_audit CHECK (
    (resolution_status IN ('RESOLVED','ACCEPTED') AND resolved_at IS NOT NULL AND resolution_note IS NOT NULL AND CHAR_LENGTH(TRIM(resolution_note)) > 0)
    OR (resolution_status IN ('OPEN','IN_REVIEW') AND resolved_at IS NULL)
);
CREATE INDEX ix_exception_status_detected ON exception_record(resolution_status, detected_at DESC);
CREATE INDEX ix_quarantine_disposition_time ON quarantined_record(disposition, quarantined_at DESC);
